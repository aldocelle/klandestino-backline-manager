import assert from 'node:assert/strict';
import {demoSeed,applyDemoCommand} from '../frontend/demo-adapter.js';
let s=demoSeed();
assert.equal(s.assets.length,73);const initial=structuredClone(s);
const cmd={type:'create_event',name:'Prueba estática',place:'Escenario A',responsible:'Krew QA',start:s.events[0].start,end:s.events[0].end,assetIds:['TAM-SCM-001-BD','TAM-SCM-001-T10']};
s=applyDemoCommand(s,cmd);const eventId=s.events.at(-1).id;
assert.equal(s.kits[0].assembled,false);assert.equal(initial.assets[0].status,'available');
assert.throws(()=>applyDemoCommand(s,cmd));
s=applyDemoCommand(s,{type:'dispatch',eventId,assetIds:cmd.assetIds});
s=applyDemoCommand(s,{type:'return',eventId,assetIds:['TAM-SCM-001-BD'],condition:'ok'});
assert.equal(s.assets.find(a=>a.id==='TAM-SCM-001-BD').status,'available');
assert.equal(s.assets.find(a=>a.id==='TAM-SCM-001-T10').status,'out');
assert.equal(s.assets.find(a=>a.id==='TAM-SCM-001-T12').status,'available');
assert.equal(s.movements.length,4);
let whole=applyDemoCommand(demoSeed(),{...cmd,assetIds:demoSeed().kits[0].expectedIds});
assert.equal(whole.assets.filter(a=>a.status==='reserved').length,14);
whole=applyDemoCommand(whole,{type:'dispatch',eventId:whole.events.at(-1).id,assetIds:whole.kits[0].expectedIds});
whole=applyDemoCommand(whole,{type:'return',eventId:whole.events.at(-1).id,assetIds:['TAM-SCM-001-BD'],condition:'damage',note:'Golpe'});
assert.equal(whole.assets.find(a=>a.id==='TAM-SCM-001-BD').status,'maintenance');
assert.throws(()=>applyDemoCommand(whole,{type:'kit_mode',kitId:'TAM-SCM-001',assembled:true}));
console.log('PASS static demo: counts, no source mutation, duplicate protection, complete kit, partial reserve/dispatch/return, damaged return and audit.');
